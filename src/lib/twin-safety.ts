export type TwinProvenance = {
  claim_generator: string;
  format: "opc-twin-provenance/1";
  assertions: Array<Record<string, unknown>>;
  outputId: string;
  createdAt: string;
};

/**
 * C2PA-style manifest (JSON). It mirrors the C2PA « c2pa.actions » assertion
 * with digitalSourceType trainedAlgorithmicMedia. Embedding a real, X.509-signed
 * C2PA manifest in the media file is done by the twin app at render time
 * (needs a signing certificate — see docs/jumeau-banque-api.md).
 */
export function twinProvenance(input: {
  outputId: string;
  licenseId: string;
  lenderRef: string;
  kind: "voice" | "image";
  outputSha256: string | null;
  createdAt: number;
}): TwinProvenance {
  return {
    claim_generator: "OPC Jumeau numérique / opencommunity.app",
    format: "opc-twin-provenance/1",
    outputId: input.outputId,
    createdAt: new Date(input.createdAt).toISOString(),
    assertions: [
      {
        label: "c2pa.actions",
        data: { actions: [{ action: "c2pa.created", digitalSourceType: TRAINED_ALGORITHMIC_MEDIA }] },
      },
      {
        label: "opc.twin.license",
        data: { licenseId: input.licenseId, lender: input.lenderRef, kind: input.kind, aiGenerated: true },
      },
      ...(input.outputSha256 ? [{ label: "c2pa.hash.data", data: { alg: "sha256", hash: input.outputSha256 } }] : []),
    ],
  };
}
