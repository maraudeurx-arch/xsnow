/** `\b` is ASCII-only in JS; rebuild each rule with a Unicode-aware word boundary (é, ñ, ç…). */
const WB = "(?:(?<=[\\p{L}\\p{N}])(?![\\p{L}\\p{N}])|(?<![\\p{L}\\p{N}])(?=[\\p{L}\\p{N}]))";
const COMPILED = RULES.map((r) => ({ reason: r.reason, re: new RegExp(r.re.source.replaceAll("\\b", WB), "iu") }));

/** null when allowed; otherwise the first matching banned-use reason. */
export function twinPromptIssue(prompt: unknown): TwinBannedReason | null {
  if (typeof prompt !== "string" || prompt.trim().length < 3) return "empty";
  const text = prompt.normalize("NFC").slice(0, 4000);
  for (const rule of COMPILED) if (rule.re.test(text)) return rule.reason;
  return null;
}

