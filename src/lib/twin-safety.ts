/** IPTC digital source type used by C2PA for AI-generated media. */
export const TRAINED_ALGORITHMIC_MEDIA = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia";

export function twinVisibleLabel(pseudonym: string, kind: "voice" | "image") {
  const who = pseudonym || "OPC";
  return {
    fr: `Contenu généré par IA — ${kind === "voice" ? "voix prêtée" : "image prêtée"} par ${who} via OPC. Cette personne n’a pas réellement dit ou fait ce qui est montré.`,
    en: `AI-generated content — ${kind === "voice" ? "voice lent" : "image lent"} by ${who} via OPC. This person did not actually say or do what is shown.`,
    es: `Contenido generado por IA — ${kind === "voice" ? "voz prestada" : "imagen prestada"} por ${who} a través de OPC. Esta persona no dijo ni hizo realmente lo que se muestra.`,
  };
}

/** Audible disclosure to read at the start of any audio/video (cahier § 7.4). */
